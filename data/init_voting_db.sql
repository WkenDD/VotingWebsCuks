-- Setup Database for Voting Web HC
CREATE DATABASE IF NOT EXISTS `wira_harapan_vote` DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_general_ci;
USE `wira_harapan_vote`;
SET FOREIGN_KEY_CHECKS = 0;
DROP TABLE IF EXISTS `vote`;
DROP TABLE IF EXISTS `detail_vote`;
DROP TABLE IF EXISTS `tokenvote`;
DROP TABLE IF EXISTS `user`;
DROP TABLE IF EXISTS `siswa`;
DROP TABLE IF EXISTS `penampilan`;
SET FOREIGN_KEY_CHECKS = 1;

CREATE TABLE `siswa` (
  `id_siswa` INT(11) NOT NULL AUTO_INCREMENT,
  `no_absen` INT(11) DEFAULT NULL,
  `tingkat` VARCHAR(10) DEFAULT NULL,
  `kelas` VARCHAR(50) NOT NULL,
  `nama` VARCHAR(255) NOT NULL,
  `jenis_kelamin` ENUM('L','P') DEFAULT 'L',
  `nis` VARCHAR(30) NOT NULL,
  `has_voted` TINYINT(1) NOT NULL DEFAULT 0,
  `voted_at` DATETIME DEFAULT NULL,
  PRIMARY KEY (`id_siswa`),
  UNIQUE KEY `nis` (`nis`),
  KEY `idx_nama` (`nama`),
  KEY `idx_kelas` (`kelas`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;


CREATE TABLE `penampilan` (
  `id_penampilan` INT(11) NOT NULL AUTO_INCREMENT,
  `nama_kelas` VARCHAR(50) NOT NULL,
  `angkatan` VARCHAR(10) NOT NULL,
  `nama_penampilan` VARCHAR(255) NOT NULL,
  `status` ENUM('aktif','nonaktif') NOT NULL DEFAULT 'aktif',
  `total_votes` INT(11) NOT NULL DEFAULT 0,
  PRIMARY KEY (`id_penampilan`),
  KEY `idx_status` (`status`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;


CREATE TABLE `vote` (
  `id_vote` INT(11) NOT NULL AUTO_INCREMENT,
  `id_siswa` INT(11) NOT NULL,
  `id_penampilan` INT(11) NOT NULL,
  `created_at` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (`id_vote`),
  KEY `idx_siswa` (`id_siswa`),
  KEY `idx_penampilan` (`id_penampilan`),
  CONSTRAINT `fk_vote_siswa` FOREIGN KEY (`id_siswa`) REFERENCES `siswa` (`id_siswa`) ON DELETE CASCADE,
  CONSTRAINT `fk_vote_penampilan` FOREIGN KEY (`id_penampilan`) REFERENCES `penampilan` (`id_penampilan`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;

